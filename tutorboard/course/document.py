CARD_RE = re.compile(r"^(\d{4})[-_.](.*)\.(md|markdown|tex)$")

SIGNAL_SAID = {
    "done": "ready to check",
    "help": "asked for help",
    "confused": "said they were lost",
    "begin": "asked the tutor to begin",
    "skip": "skipped this one",
}


def front_matter(raw):
    """The `---` block at the top of a card, and the body under it."""
    meta = {}
    text = raw
    if raw.startswith("---"):
        end = raw.find("\n---", 3)
        if end != -1:
            for line in raw[3:end].splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    meta[k.strip().lower()] = v.strip()
            text = raw[end + 4:].lstrip("\n")
    return meta, text


def read_cards(folder):
    """Every card in one lesson folder, in the order they were written."""
    out = []
    try:
        names = sorted(n for n in os.listdir(folder) if CARD_RE.match(n))
    except OSError:
        return out
    for n in names:
        try:
            with open(os.path.join(folder, n), "r", encoding="utf-8") as fh:
                raw = fh.read()
            st = os.stat(os.path.join(folder, n))
        except OSError:
            continue
        meta, text = front_matter(raw)
        # The same gate the board reads through: a document is not the place to
        # preserve a model's private working either.
        text = reasoning.card_body(text)
        out.append({"id": CARD_RE.match(n).group(1),
                    "kind": (meta.get("kind") or "lesson").lower(),
                    "title": meta.get("title", ""),
                    "body": text,
                    "mtime": st.st_mtime})
    return out


def read_turns(path):
    """EVERY revision of every turn, oldest first.

    The board collapses a turn to its newest revision, because three sends of one
    proof are one attempt and showing three is a lie about how many times the
    student answered. A document read by somebody who was not there is the
    opposite case: the point of it is the work, and the work is the sequence --
    what was handed in, what came back, what changed. So nothing is collapsed
    here, and each revision says which attempt it is.
    """
    out = []
    try:
        with open(path, "r", encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except ValueError:
                    continue
                if rec.get("id"):
                    out.append(rec)
    except OSError:
        return []
    out.sort(key=lambda r: (r.get("t") or 0, r.get("rev") or 0))
    return out


def reading_order(cards, turns):
    """Cards and turns interleaved the way the board reads them on screen.

    A turn belongs under the question it answers, whatever time it arrived --
    which is the rule the board itself uses, and it matters here because a
    student who goes back to an earlier exercise must not have that answer filed
    at the end of the document, half an hour of somebody else's questions away
    from the thing it is answering.
    """
    at = {}
    for n, c in enumerate(cards):
        at[c["id"]] = n
    items = []
    for n, c in enumerate(cards):
        items.append((n, 0, c.get("mtime") or 0, "card", c))
    for t in turns:
        when = t.get("t") or 0
        if t.get("answers") in at:
            pos = at[t["answers"]]
        else:
            pos = -1
            for n, c in enumerate(cards):
                if (c.get("mtime") or 0) <= when:
                    pos = n
        items.append((pos, 1, when, "turn", t))
    items.sort(key=lambda it: (it[0], it[1], it[2]))
    return [(kind, obj) for _, _, _, kind, obj in items]


def _attempt_numbers(turns):
    """Which attempt each revision is, per question, in time order."""
    seen = {}
    out = {}
    for t in turns:
        if t.get("kind") not in ("ink", "text"):
            continue
        q = t.get("answers") or ""
        seen[q] = seen.get(q, 0) + 1
        out[id(t)] = seen[q]
    return out


def _picture(answers_dir, url):
    """One handed-in page, as the picture that was actually sent.

    Relative to the repository root, never absolute: the `.tex` is committed
    beside the PNGs it names, so it has to still build on somebody else's
    machine. `build` runs LaTeX from the root for exactly this reason.
    """
    if not url:
        return None
    name = url.split("/answers/", 1)[-1]
    path = os.path.join(answers_dir, name)
    if not os.path.exists(path):
        return None
    return path


def render_lesson(cards_dir, turns_path, answers_dir, root, heading=None):
    """One sitting as LaTeX: the questions, the working, and the replies."""
    cards = read_cards(cards_dir)
    turns = read_turns(turns_path)
    if not cards and not turns:
        return []
    attempt = _attempt_numbers(turns)
    of = {}
    for t in turns:
        if id(t) in attempt:
            q = t.get("answers") or ""
            of[q] = max(of.get(q, 0), attempt[id(t)])

    body = []
    if heading:
        body.append("\\section{%s}" % inline_tex(heading))
    for kind, obj in reading_order(cards, turns):
        if kind == "card":
            head = KIND_HEAD.get(obj["kind"])
            label = " -- ".join(x for x in (head, obj["title"]) if x)
            if label:
                body.append("\\needspace{3\\baselineskip}\\subsection*{%s}"
                            % inline_tex(label))
            body.append(md_to_tex(obj["body"]))
            body.append("")
            continue

        t = obj
        who = "You" if (t.get("from") or "student") == "student" else "The tutor"
        n, total = attempt.get(id(t)), of.get(t.get("answers") or "", 0)
        when = t.get("iso") or ""
        if t.get("kind") == "ink":
            say = "%s wrote" % who
            if total > 1 and n:
                say += " -- attempt %d of %d" % (n, total)
            if when:
                say += ", %s" % when
            path = _picture(answers_dir, t.get("png"))
            body.append("\\begin{studentturn}{%s}" % inline_tex(say))
            if path:
                body.append("\\begin{center}\\includegraphics"
                            "[width=0.95\\linewidth,height=0.78\\textheight,"
                            "keepaspectratio]{%s}\\end{center}"
                            % os.path.relpath(path, root).replace("\\", "/"))
            else:
                body.append("\\emph{(the page this answer was written on is not "
                            "in this repository)}")
            body.append("\\end{studentturn}")
            body.append("")
        elif t.get("kind") == "text":
            said = SIGNAL_SAID.get(t.get("signal") or "")
            say = "%s said" % who
            if total > 1 and n:
                say += " -- attempt %d of %d" % (n, total)
            if when:
                say += ", %s" % when
            body.append("\\begin{studentturn}{%s}" % inline_tex(say))
            if said and not (t.get("text") or "").strip():
                body.append("\\emph{%s}" % inline_tex(said))
            else:
                if said:
                    body.append("\\emph{%s}\\par\\smallskip" % inline_tex(said))
                body.append(md_to_tex(t.get("text") or ""))
            body.append("\\end{studentturn}")
            body.append("")
        elif t.get("kind") == "annotation":
            say = "%s marked up the card" % who
            if when:
                say += ", %s" % when
            path = _picture(answers_dir, t.get("png"))
            body.append("\\begin{studentturn}{%s}" % inline_tex(say))
            if path:
                body.append("\\begin{center}\\includegraphics"
                            "[width=0.95\\linewidth,height=0.5\\textheight,"
                            "keepaspectratio]{%s}\\end{center}"
                            % os.path.relpath(path, root).replace("\\", "/"))
            body.append("\\end{studentturn}")
            body.append("")
    return body


