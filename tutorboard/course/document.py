def author_name(live):
    """Whose name goes on an exported lesson: state.json, then git, then nobody."""
    name = live.state().get("author")
    if name:
        return name
    try:
        p = subprocess.run(["git", "config", "user.name"], cwd=live.root,
                           stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=5)
        if p.returncode == 0:
            return p.stdout.decode("utf-8", "replace").strip()
    except (OSError, subprocess.TimeoutExpired):
        pass
    return ""


