def slugify(s):
    s = re.sub(r"[^A-Za-z0-9]+", "-", (s or "").strip().lower()).strip("-")
    return (s or "lesson")[:48]


def next_version(out_dir, stem):
    """v1, v2, v3 -- and never a timestamp.

    Asked for in those words: a name stamped with the time is an eyesore and it
    does not answer the only question anybody asks of a folder of exports, which
    is which one is the latest. The number is one more than the highest already
    there, counting both halves of a pair, so a `.tex` written by a build whose
    LaTeX then failed still consumes its number rather than being quietly
    overwritten by the next attempt.
    """
    high = 0
    try:
        names = os.listdir(out_dir)
    except OSError:
        return 1
    pat = re.compile(re.escape(stem) + r"-v(\d+)\.(pdf|tex)$")
    for n in names:
        m = pat.match(n)
        if m:
            high = max(high, int(m.group(1)))
    return high + 1


def read_state(path):
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh) or {}
    except (OSError, ValueError):
        return {}


def lessons(root, scope="lesson"):
    """The sittings to put in the document, oldest first.

    A lesson is the unit -- one sitting, one document, numbered v1, v2, v3 as it
    is exported again. `scope="all"` is the other thing somebody shows a
    professor: every filed lesson in the course, then the one still open, as a
    single master document.
    """
    live = os.path.join(root, "live")
    here = {"cards": os.path.join(live, "cards"),
            "turns": os.path.join(live, "turns.jsonl"),
            "answers": os.path.join(live, "answers"),
            "state": read_state(os.path.join(live, "state.json"))}
    if scope != "all":
        return [here]
    out = []
    archive = os.path.join(live, "archive")
    try:
        names = sorted(os.listdir(archive))
    except OSError:
        names = []
    for name in names:
        folder = os.path.join(archive, name)
        if not os.path.isdir(folder):
            continue
        out.append({"cards": folder,
                    "turns": os.path.join(folder, "turns.jsonl"),
                    "answers": os.path.join(folder, "answers"),
                    "state": read_state(os.path.join(folder, "state.json")),
                    "filed": name})
    if read_cards(here["cards"]) or read_turns(here["turns"]):
        out.append(here)
    return out


