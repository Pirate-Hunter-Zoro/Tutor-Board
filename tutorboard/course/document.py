def tex_unicode(s):
    """Make a string something pdflatex will actually read."""
    out = []
    for ch in s:
        if ord(ch) < 128 or 0xA0 < ord(ch) < 0x180:
            out.append(ch)
        elif ch in UNICODE_TEXT:
            out.append(UNICODE_TEXT[ch])
        elif ch in UNICODE_TEX:
            out.append("\\ensuremath{%s}" % UNICODE_TEX[ch])
        else:
            out.append("")            # better a missing glyph than no document
    return "".join(out)


def tex_escape(s):
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"),
                 ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}")):
        s = s.replace(a, b)
    return s


def md_to_tex(body):
    """Enough markdown for a lesson transcript. Math and tikz pass through."""
    out = []
    lines = tex_unicode(body).replace("\r\n", "\n").split("\n")
    i = 0
    list_stack = []

    def close_lists(to=0):
        while len(list_stack) > to:
            out.append("\\end{%s}" % list_stack.pop())

    while i < len(lines):
        line = lines[i]

        m = re.match(r"^[ \t]*```[ \t]*(tikz|tikzcd|latex)[ \t]*$", line)
        if m:
            kind = m.group(1)
            i += 1
            buf = []
            while i < len(lines) and not re.match(r"^[ \t]*```", lines[i]):
                buf.append(lines[i])
                i += 1
            i += 1
            src = "\n".join(buf)
            if kind == "tikzcd" and "\\begin{tikzcd}" not in src:
                src = "\\begin{tikzcd}\n%s\n\\end{tikzcd}" % src
            elif kind == "tikz" and "\\begin{tikzpicture}" not in src and "\\begin{tikzcd}" not in src:
                src = "\\begin{tikzpicture}\n%s\n\\end{tikzpicture}" % src
            close_lists()
            out.append("\\begin{center}\n%s\n\\end{center}" % src)
            continue

        if not line.strip():
            close_lists()
            out.append("")
            i += 1
            continue

        h = re.match(r"^(#{1,6})\s+(.*)$", line)
        if h:
            close_lists()
            level = len(h[1])
            cmd = "subsection*" if level >= 2 else "section*"
            if level >= 3:
                cmd = "subsubsection*"
            out.append("\\%s{%s}" % (cmd, inline_tex(h[2])))
            i += 1
            continue

        if re.match(r"^\s*(-{3,}|\*{3,}|_{3,})\s*$", line):
            close_lists()
            out.append("\\medskip\\hrule\\medskip")
            i += 1
            continue

        # table
        if "|" in line and i + 1 < len(lines) and re.match(r"^\s*\|?[\s:|-]*-[\s:|-]*\|?\s*$", lines[i + 1]):
            close_lists()
            rows = []
            header = [c.strip() for c in line.strip().strip("|").split("|")]
            i += 2
            while i < len(lines) and "|" in lines[i] and lines[i].strip():
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            spec = "l" * len(header)
            out.append("\\begin{center}\\begin{tabular}{%s}\\hline" % spec)
            out.append(" & ".join("\\textbf{%s}" % inline_tex(c) for c in header) + " \\\\ \\hline")
            for r in rows:
                out.append(" & ".join(inline_tex(c) for c in r) + " \\\\")
            out.append("\\hline\\end{tabular}\\end{center}")
            continue

        b = re.match(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$", line)
        if b:
            depth = len(b[1]) // 2 + 1
            env = "enumerate" if re.match(r"\d", b[2]) else "itemize"
            while len(list_stack) > depth:
                out.append("\\end{%s}" % list_stack.pop())
            while len(list_stack) < depth:
                list_stack.append(env)
                out.append("\\begin{%s}" % env)
            out.append("  \\item " + inline_tex(b[3]))
            i += 1
            continue

        if line.lstrip().startswith(">"):
            close_lists()
            buf = []
            while i < len(lines) and lines[i].lstrip().startswith(">"):
                buf.append(re.sub(r"^\s*>\s?", "", lines[i]))
                i += 1
            out.append("\\begin{quote}\n%s\n\\end{quote}" % inline_tex(" ".join(buf)))
            continue

        close_lists()
        out.append(inline_tex(line))
        i += 1

    close_lists()
    return "\n".join(out)


def inline_tex(s):
    """Markdown emphasis and code to LaTeX, leaving math spans alone."""
    s = tex_unicode(s)
    parts = re.split(r"(\$\$.*?\$\$|\$[^$]*\$|\\\[.*?\\\]|\\\(.*?\\\))", s, flags=re.DOTALL)
    for n, part in enumerate(parts):
        if n % 2:
            continue
        part = re.sub(r"`([^`]+)`", lambda m: "\\texttt{%s}" % tex_escape(m.group(1)), part)
        part = re.sub(r"\*\*\*(.+?)\*\*\*", r"\\textbf{\\emph{\1}}", part)
        part = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", part)
        part = re.sub(r"(?<![\w*])\*([^*\n]+)\*(?![\w*])", r"\\emph{\1}", part)
        part = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r"\\href{\2}{\1}", part)
        for a, b in (("&", "\\&"), ("%", "\\%"), ("#", "\\#")):
            part = part.replace(a, b)
        part = re.sub(r"(?<![\\{])_", r"\\_", part)
        parts[n] = part
    return "".join(parts)




