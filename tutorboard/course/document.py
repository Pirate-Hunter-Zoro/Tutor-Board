def heading_for(sitting):
    """A lesson's name in the master document.

    Two sittings on the same chapter are the ordinary case -- an exercise runs
    over two evenings -- so the heading has to separate them, and `state.json`
    cannot: the live one carries whatever `opened` said when the chapter was
    opened, which is the same string. The archive folder is stamped with the
    moment the lesson was FILED, which is the one thing that differs, and the
    lesson still open says so in words rather than borrowing a date.
    """
    st = sitting.get("state") or {}
    bits = [st.get("chapter") or st.get("course") or "Lesson"]
    kind = st.get("session") or ""
    if kind and kind != "lecture":
        bits.append(kind.replace("_", " "))
    label = " -- ".join(bits)
    filed = sitting.get("filed") or ""
    m = re.match(r"^(\d{4})(\d{2})(\d{2})-(\d{2})(\d{2})", filed)
    if m:
        return "%s (%s-%s-%s %s:%s)" % (label, m.group(1), m.group(2), m.group(3),
                                        m.group(4), m.group(5))
    when = st.get("opened") or ""
    return label + (" (in progress)" if not filed else (" (%s)" % when if when else ""))


def compile_pdf(root, tex_path):
    """Twice, from the repository root, so relative image paths resolve."""
    env = tex.tex_env([os.path.join(root, "latex"), os.path.join(TOOL, "tex")])
    outdir = os.path.dirname(tex_path)
    pdf = os.path.splitext(tex_path)[0] + ".pdf"
    rel = os.path.relpath(tex_path, root)
    out = ""
    for _ in range(2):
        try:
            p = subprocess.run(
                ["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
                 "-output-directory=" + os.path.relpath(outdir, root), rel],
                cwd=root, env=env, stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT, timeout=300)
            out = p.stdout.decode("utf-8", "replace")
        except (OSError, subprocess.TimeoutExpired) as e:
            return False, "could not run pdflatex: %s" % e
    if not os.path.exists(pdf):
        log = os.path.splitext(tex_path)[0] + ".log"
        detail = ""
        if os.path.exists(log):
            with open(log, "r", encoding="utf-8", errors="replace") as fh:
                detail = "".join(ln for ln in fh if ln.startswith("!"))[:500]
        # The log stays -- it is the only account of what went wrong -- but the
        # rest of the scratch does not.
        for ext in (".aux", ".out", ".toc"):
            try:
                os.remove(os.path.splitext(tex_path)[0] + ext)
            except OSError:
                pass
        return False, (detail or out[-500:] or "LaTeX produced no PDF")
    # The aux files are not the document and have no business in the history.
    for ext in (".aux", ".out", ".toc", ".log"):
        try:
            os.remove(os.path.splitext(tex_path)[0] + ext)
        except OSError:
            pass
    return True, pdf


def track(root, paths):
    """Stage the export, so the next push carries it.

    Staged rather than committed: an export happens in the middle of a lesson and
    a commit in the middle of a lesson is a decision the person makes, not one a
    button makes for them. `board push` -- and the board's own save -- commit
    everything staged, so this goes with the next one either way.
    """
    rel = [os.path.relpath(p, root) for p in paths if os.path.exists(p)]
    if not rel:
        return False
    try:
        p = subprocess.run(["git", "add", "--"] + rel, cwd=root,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=30)
        return p.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def build(root, scope="lesson", make_pdf=True):
    """The whole conversation as one document, numbered and tracked.

    Returns a record the board can paint: what it is called, whether LaTeX
    agreed, and where it went.
    """
    sittings = lessons(root, scope)
    sittings = [s for s in sittings
                if read_cards(s["cards"]) or read_turns(s["turns"])]
    if not sittings:
        return {"ok": False, "detail": "there is no lesson here to export yet"}

    last = sittings[-1]["state"] or {}
    course = last.get("course") or os.path.basename(root)
    if scope == "all":
        title = course
        stem = slugify(course) + "-complete"
    else:
        title = last.get("chapter") or course or "Lesson"
        stem = slugify(title)

    body = []
    for s in sittings:
        body.extend(render_lesson(s["cards"], s["turns"], s["answers"], root,
                                  heading_for(s) if scope == "all" else None))

    out_dir = os.path.join(root, OUT_DIR)
    os.makedirs(out_dir, exist_ok=True)
    version = next_version(out_dir, stem)
    name = "%s-v%d" % (stem, version)
    tex_path = os.path.join(out_dir, name + ".tex")

    sty = os.path.join(root, "latex", "coursemacros.sty")
    with open(tex_path, "w", encoding="utf-8") as fh:
        fh.write(TEX_HEAD % {
            "title": inline_tex(title),
            "author": inline_tex(author_name(root, last)),
            "date": time.strftime("%B %d, %Y"),
            "macros": "\\usepackage{coursemacros}\n" if os.path.exists(sty) else "",
        })
        if scope == "all":
            fh.write("\\tableofcontents\n\\clearpage\n")
        fh.write("\n".join(body))
        fh.write("\n\\end{document}\n")

    rec = {"ok": True, "name": name, "version": version, "scope": scope,
           "tex": os.path.relpath(tex_path, root), "pdf": None, "detail": ""}
    if make_pdf:
        ok, res = compile_pdf(root, tex_path)
        if ok:
            rec["pdf"] = os.path.relpath(res, root)
        else:
            rec["ok"] = False
            rec["detail"] = res
    rec["tracked"] = track(root, [tex_path,
                                  os.path.join(out_dir, name + ".pdf")])
    return rec
